               ( corner4 != MaterialIndex.Void ? 1 << 4 : 0 ) |
               ( corner5 != MaterialIndex.Void ? 1 << 5 : 0 ) |
               ( corner6 != MaterialIndex.Void ? 1 << 6 : 0 ) |
               ( corner7 != MaterialIndex.Void ? 1 << 7 : 0 );
    }

