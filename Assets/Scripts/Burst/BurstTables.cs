    // DualMarchingCubes.lookupSeparation
    public static bool lookupSeparation( int solidCorners, int vertex, int other, out Unity.Mathematics.int3 normal, out int twiceOffset ) {
        normal      = Unity.Mathematics.int3.zero;
        twiceOffset = 0;

        var count = vertexCounts[solidCorners];

        if( vertex == other || vertex < 0 || other < 0 || vertex >= count || other >= count ) {
            return false;
        }

        var lower  = vertex < other ? vertex : other;
        var higher = vertex < other ? other : vertex;
        var entry  = ( ( ( solidCorners * 6 ) + ( lower * ( 7 - lower ) / 2 ) + ( higher - lower - 1 ) ) * 4 );
        var sign   = vertex < other ? 1 : -1;

        normal      = new Unity.Mathematics.int3( separations[entry], separations[entry + 1], separations[entry + 2] ) * sign;
        twiceOffset = separations[entry + 3] * sign;

        return true;
    }

    // DualMarchingCubes.sharesJoinedFace
    public static bool sharesJoinedFace( int solidCorners, int solidCornersAcross ) {
        var face  = joinedFaces[solidCorners];
        var other = joinedFaces[solidCornersAcross];

        return face != -1 && other != -1 && faceAxes[face] == faceAxes[other] && faceSides[face] != faceSides[other];
    }

